// Regenerates site/data.js from the exported portfolio manifests.
// Usage: node site/tools/build-data.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const SRC = join(here, '..', '..', 'compassandtrail-portfolio');
const OUT = join(here, '..', 'data.js');

// Presentation settings that are not in the export: kind label, cover image, short facts.
const meta = {
  'tchagra-trails-greater-kruger-national-park': { kind: 'Expedition', cover: '011', facts: ['6 days', 'Big-5 territory', 'On foot'], short: 'Tchagra Trails', region: 'Greater Kruger National Park' },
  'queen-rose-trails': { kind: 'Trail', cover: '020', facts: ['4 days', '4 trails'], short: 'Queen Rose Trails' },
  'magalies-krans-trail': { kind: 'Trail', cover: '006', facts: ['2 days', 'Solo', 'Overnight'], short: 'Magalies Krans', region: 'Hartbeespoort' },
  'magoebaskloof-trail': { kind: 'Trail', cover: '004', facts: ['6 days', 'Cloud forest'], short: 'Magoebaskloof', region: 'Wolkberg, Limpopo' },
  'wildlife': { kind: 'Series', cover: '003', facts: ['Black & white'], short: 'Wildlife' },
  'cac-june-2024': { kind: 'Event', cover: '007', facts: ['Mountain biking'], short: 'CAC June 2024' },
  'sports-science-lab-promo': { kind: 'Commission', cover: '012', facts: ['Promotional shoot'], short: 'Sports Science Lab' },
};
const order = Object.keys(meta);
const YT = /https?:\/\/(www\.)?youtube\.com\/watch\?v=[\w-]+/;

function load(folder) {
  const m = JSON.parse(readFileSync(join(SRC, folder, 'manifest.json'), 'utf8'));
  const links = [...m.links];
  // Drop paragraphs that are only a URL or "here: URL"; the link becomes a button instead.
  const blurb = m.description
    .map((p) => p.trim())
    .filter((p) => !/^https?:\/\/\S+$/.test(p) && !/^YouTube video can be found here:/i.test(p));
  return {
    slug: folder,
    title: m.title,
    blurb,
    video: links.find((l) => YT.test(l)) || null,
    images: m.images.map((i) => ({
      id: i.file.replace(/\.\w+$/, ''),
      w: i.file_width, h: i.file_height,
      // Skip export artefacts like "Magalies Krans YouTube Cover - 3" or "QUEEN ROSE TRAILS - D1 - 3".
      caption: i.caption && !/youtube cover/i.test(i.caption) && !/^[A-Z0-9 \-]+$/.test(i.caption) ? i.caption : null,
    })),
  };
}

const gallery = load('portfolio');
const projects = order.map((slug) => ({ ...load(slug), ...meta[slug] }));
const home = JSON.parse(readFileSync(join(SRC, 'home', 'manifest.json'), 'utf8'));

const data = {
  name: 'Kevin Baynham',
  brand: 'Compass & Trail',
  tagline: home.description[1] || 'Scenes from adventures',
  social: [
    { label: 'YouTube', url: 'https://urlgeni.us/youtube/channel/compassandtrail', icon: 'img/icons/001.png' },
    { label: 'Instagram', url: 'https://www.instagram.com/compass_and_trail/', icon: 'img/icons/002.png' },
    { label: 'Threads', url: 'https://www.threads.net/@compass_and_trail', icon: 'img/icons/003.png' },
    { label: 'Gear list', url: 'https://lighterpack.com/r/fyp7ac', icon: 'img/icons/004.png' },
  ],
  hero: [
    ['portfolio', '012'], ['tchagra-trails-greater-kruger-national-park', '008'], ['queen-rose-trails', '020'],
    ['portfolio', '052'], ['magoebaskloof-trail', '003'], ['portfolio', '073'],
  ],
  gallery,
  projects,
};
writeFileSync(OUT, `// Generated by tools/build-data.mjs — do not edit by hand.\nwindow.SITE = ${JSON.stringify(data, null, 1)};\n`);
console.log(`Wrote ${OUT}: ${gallery.images.length} gallery images, ${projects.length} projects`);
